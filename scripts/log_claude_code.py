#!/usr/bin/env python3
"""
Claude Code transcript scanner -- extracts the exact prompts the student typed.

Why this exists
---------------
The pre-push hook only ran ``log_antigravity.py``, which reads Antigravity IDE
transcripts. Work done in Claude Code left no trace at all: every push printed
"No new prompts" and ``.ai-log/`` stayed empty, so none of it reached the
grading server. The collector was not broken -- it was looking in the one place
the prompts were not.

Source of truth
    ~/.claude/projects/<project-slug>/<session-id>.jsonl

Each line is a JSON object. A line counts as a student prompt when
``type == "user"`` and it is not one of the many things that merely *look* like
user turns in that file:

  - ``isMeta``            -- harness-injected context, never typed
  - ``isSidechain``       -- a subagent's own conversation
  - ``tool_result`` blocks -- output being fed back to the model
  - ``<local-command-caveat>`` -- the echo of a slash command such as /compact
  - ``<system-reminder>`` -- background context injected by the harness

Without those exclusions the file reports ~780 "user" turns for what were
actually 36 prompts, which would drown the real ones in tool output.

Usage:
  python scripts/log_claude_code.py --auto          # default: last 24h
  python scripts/log_claude_code.py --all           # every session, no cutoff
  python scripts/log_claude_code.py --hours 72
  python scripts/log_claude_code.py --dry-run       # preview only

Env overrides:
  CLAUDE_PROJECTS_DIR  point at a different projects/ directory
  AI_LOG_DIR           where session.jsonl is written (default: .ai-log)
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path

VN_TZ = timezone(timedelta(hours=7))

# Wrappers the harness puts around a real prompt. The prompt inside them is
# genuinely the student's, so they are stripped rather than used to reject.
_STRIP_BLOCKS = (
    re.compile(r"<ide_opened_file>.*?</ide_opened_file>", re.DOTALL),
    re.compile(r"<ide_selection>.*?</ide_selection>", re.DOTALL),
    re.compile(r"<system-reminder>.*?</system-reminder>", re.DOTALL),
)

# Prefixes that mark a line as machinery rather than something a person typed.
# All of these arrive on the "user" channel and are indistinguishable from a
# prompt by type alone: slash-command output, background-task notifications the
# runtime posts to itself, and the summary written when a conversation is
# compacted. Logging them would credit the student with prompts they never
# wrote and bury the ones they did.
_REJECT_PREFIXES = (
    "<local-command-caveat>",
    "<local-command-stdout>",
    "<command-name>",
    "<command-message>",
    "<task-notification>",
    "[SYSTEM NOTIFICATION",
    "Caveat: The messages below were generated by the user",
    "This session is being continued from a previous conversation",
)


def git(cmd: str) -> str:
    try:
        return subprocess.check_output(
            cmd, shell=True, text=True, stderr=subprocess.DEVNULL
        ).strip()
    except Exception:
        return ""


def project_slug(repo_root: Path) -> str:
    """Claude Code's on-disk name for a project directory.

    ``d:\\TEAM159\\P-159`` becomes ``d--TEAM159-P-159``: every separator, drive
    colon included, collapses to a dash.
    """
    return re.sub(r"[:\\/]", "-", str(repo_root))


def projects_dir() -> Path:
    override = os.environ.get("CLAUDE_PROJECTS_DIR")
    if override:
        return Path(override)
    return Path.home() / ".claude" / "projects"


def session_files(repo_root: Path) -> list[Path]:
    """Transcripts for this repo, by directory name and then by content.

    The slug is derived from the path, so a repo reached through a different
    drive letter or casing would miss. Falling back to the ``cwd`` recorded
    inside each transcript makes the match hold anyway.
    """
    base = projects_dir()
    if not base.is_dir():
        return []

    exact = base / project_slug(repo_root)
    if exact.is_dir():
        found = sorted(exact.glob("*.jsonl"))
        if found:
            return found

    wanted = str(repo_root).replace("\\", "/").lower().rstrip("/")
    matches: list[Path] = []
    for path in sorted(base.glob("*/*.jsonl")):
        try:
            with open(path, encoding="utf-8", errors="replace") as handle:
                for _ in range(40):
                    line = handle.readline()
                    if not line:
                        break
                    try:
                        record = json.loads(line)
                    except json.JSONDecodeError:
                        continue
                    cwd = str(record.get("cwd") or "").replace("\\", "/").lower()
                    if cwd and cwd.rstrip("/") == wanted:
                        matches.append(path)
                        break
        except OSError:
            continue
    return matches


def extract_text(message: dict) -> str:
    """The typed text of one user turn, or "" if this turn was not typed."""
    content = message.get("content")
    if isinstance(content, str):
        return content
    if not isinstance(content, list):
        return ""
    # A turn carrying tool output is the harness answering the model, not a
    # person answering it.
    if any(
        isinstance(block, dict) and block.get("type") == "tool_result"
        for block in content
    ):
        return ""
    return "\n".join(
        str(block.get("text") or "")
        for block in content
        if isinstance(block, dict) and block.get("type") == "text"
    )


def clean(text: str) -> str:
    for pattern in _STRIP_BLOCKS:
        text = pattern.sub("", text)
    return text.strip()


def is_student_prompt(record: dict) -> bool:
    if record.get("type") != "user":
        return False
    if record.get("isMeta") or record.get("isSidechain"):
        return False
    return record.get("userType", "external") == "external"


def iter_prompts(files: list[Path], cutoff: datetime | None):
    """Yield (timestamp, session_id, uuid, text) for real prompts, oldest first."""
    collected = []
    for path in files:
        session_id = path.stem
        try:
            handle = open(path, encoding="utf-8", errors="replace")
        except OSError:
            continue
        with handle:
            for line in handle:
                line = line.strip()
                if not line:
                    continue
                try:
                    record = json.loads(line)
                except json.JSONDecodeError:
                    continue
                if not is_student_prompt(record):
                    continue

                raw = extract_text(record.get("message") or {})
                if not raw.strip():
                    continue
                if any(raw.lstrip().startswith(p) for p in _REJECT_PREFIXES):
                    continue

                text = clean(raw)
                if not text:
                    continue

                ts = str(record.get("timestamp") or "")
                if cutoff and ts:
                    try:
                        moment = datetime.fromisoformat(ts.replace("Z", "+00:00"))
                        if moment < cutoff:
                            continue
                    except ValueError:
                        pass

                collected.append(
                    (ts, session_id, str(record.get("uuid") or ""), text)
                )

    collected.sort(key=lambda item: item[0])
    return collected


def build_entry(
    ts: str,
    session_id: str,
    uuid: str,
    text: str,
    *,
    repo: str,
    branch: str,
    commit: str,
    student: str,
) -> dict:
    # Stable across runs: the same prompt must produce the same id every time,
    # or every push resubmits the whole history.
    seed = uuid or hashlib.sha256(f"{ts}|{text}".encode()).hexdigest()[:16]
    return {
        "ts": ts or datetime.now(VN_TZ).isoformat(),
        "tool": "claude-code",
        "event": "TaskComplete",
        "entry_id": f"claude-code-{session_id[:8]}-{seed[:12]}",
        "model": os.environ.get("CLAUDE_MODEL", "claude-opus-5"),
        "repo": repo,
        "branch": branch,
        "commit": commit,
        "student": student,
        "prompt": text[:1000],
        "response_summary": f"[Claude Code] {text[:300]}",
    }


def logged_entry_ids(log_dir: Path) -> set[str]:
    """Ids already recorded, including ones already submitted and archived.

    The archive matters: ``submit_log.py`` moves entries out of
    ``session.jsonl`` once the server accepts them, so a dedup check that reads
    only the live file re-sends the entire history on the next push.
    """
    seen: set[str] = set()
    candidates = [log_dir / "session.jsonl"]
    candidates.extend(sorted((log_dir / "archive").glob("*.jsonl")))
    for path in candidates:
        if not path.exists():
            continue
        try:
            handle = open(path, encoding="utf-8-sig", errors="replace")
        except OSError:
            continue
        with handle:
            for line in handle:
                line = line.strip()
                if not line:
                    continue
                try:
                    entry = json.loads(line)
                except json.JSONDecodeError:
                    continue
                if entry.get("entry_id"):
                    seen.add(entry["entry_id"])
    return seen


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--auto", action="store_true", help="Hook mode.")
    parser.add_argument("--all", action="store_true",
                        help="Every session, no time cutoff.")
    parser.add_argument("--hours", type=int, default=24,
                        help="Window in hours when scanning (default: 24).")
    parser.add_argument("--dry-run", action="store_true",
                        help="Preview without writing.")
    args = parser.parse_args()

    repo_root = Path.cwd()
    files = session_files(repo_root)
    if not files:
        print(f"[claude-code-log] No transcripts under {projects_dir()}.",
              file=sys.stderr)
        return 0

    cutoff = None
    if not args.all:
        cutoff = datetime.now(tz=timezone.utc) - timedelta(hours=args.hours)

    log_dir = Path(os.environ.get("AI_LOG_DIR", ".ai-log"))
    log_dir.mkdir(parents=True, exist_ok=True)
    seen = logged_entry_ids(log_dir)

    repo = git("git remote get-url origin").split("/")[-1].replace(".git", "")
    branch = git("git rev-parse --abbrev-ref HEAD")
    commit = git("git rev-parse --short HEAD")
    student = git("git config user.email") or os.environ.get(
        "USERNAME", os.environ.get("USER", "unknown")
    )

    new_entries: list[dict] = []
    for ts, session_id, uuid, text in iter_prompts(files, cutoff):
        entry = build_entry(
            ts, session_id, uuid, text,
            repo=repo or repo_root.name,
            branch=branch,
            commit=commit,
            student=student,
        )
        if entry["entry_id"] in seen:
            continue
        seen.add(entry["entry_id"])
        new_entries.append(entry)

    if not new_entries:
        scope = "all" if args.all else f"{args.hours}h"
        print(f"[claude-code-log] No new prompts "
              f"({len(files)} transcript(s), window={scope}).", file=sys.stderr)
        return 0

    if args.dry_run:
        print(f"\n[claude-code-log] DRY RUN -- would log "
              f"{len(new_entries)} entries:\n")
        for entry in new_entries:
            preview = entry["prompt"].replace("\n", " ")[:120]
            print(f"  [{entry['ts'][:19]}] {preview}")
        return 0

    with open(log_dir / "session.jsonl", "a", encoding="utf-8") as handle:
        for entry in new_entries:
            handle.write(json.dumps(entry, ensure_ascii=False) + "\n")

    print(f"[claude-code-log] Logged {len(new_entries)} prompt(s) from "
          f"Claude Code.", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
